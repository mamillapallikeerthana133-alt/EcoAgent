# ============================================================

def generate_report(device_data, decision, impact):
    """
    Generate a text report for the latest EcoAgent analysis.
    """

    report = f"""
============================================================
                    ECOAGENT REPORT
          Smart E-Waste Life Extension Agent
============================================================

DEVICE INFORMATION
------------------------------------------------------------
Device Type        : {device_data.get("device_type", "N/A")}
Brand              : {device_data.get("brand", "N/A")}
Model              : {device_data.get("model", "N/A")}
Age                : {device_data.get("age", "N/A")} years
Physical Condition : {device_data.get("physical_condition", "N/A")}
Power Status       : {device_data.get("power_status", "N/A")}
Battery Condition  : {device_data.get("battery_condition", "N/A")}
Main Problem       : {device_data.get("main_problem", "N/A")}

RAM                : {device_data.get("ram", "N/A")}
Storage            : {device_data.get("storage", "N/A")}

RECENT UPGRADE / REPAIR
------------------------------------------------------------
{device_data.get("recent_upgrade", "N/A")}

RECOMMENDATION
------------------------------------------------------------
{decision.get("recommendation", "N/A")}

WHY THIS RECOMMENDATION?
------------------------------------------------------------
{decision.get("reason", "N/A")}

SUGGESTED ACTIONS
------------------------------------------------------------
"""

    actions = decision.get("actions", [])

    for number, action in enumerate(actions, start=1):
        report += f"{number}. {action}\n"

    report += f"""
ENVIRONMENTAL IMPACT
------------------------------------------------------------
Device Mass Kept in Use : {impact.get("device_weight", "N/A")} kg
Potential Useful Life   : {impact.get("useful_life", "N/A")}

------------------------------------------------------------
EcoAgent helps extend the useful life of electronic devices
and reduce unnecessary e-waste.

                    Generated by EcoAgent
============================================================
"""

    return report